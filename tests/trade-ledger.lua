local fresh,test,equal,truth,secret=...
local function world()
    local w,A=fresh();w:load();w.given,w.received=0,0
    GetPlayerTradeMoney=function()w.tradeReads=(w.tradeReads or 0)+1;return w.given end
    GetTargetTradeMoney=function()w.tradeReads=(w.tradeReads or 0)+1;return w.received end
    return w,A,A.Transactions,A.Ledger
end
local function offer(w,given,received)
    w.given,w.received=given,received;w:event("TRADE_SHOW");w:event("TRADE_ACCEPT_UPDATE",1,1)
end
local function complete(w)w:event("UI_INFO_MESSAGE",1,ERR_TRADE_COMPLETE)end

test("received trade gold is recorded only after the completed trade message",function()
    local w,A,T,L=world();offer(w,0,12345);equal(#L.Records(),0);w:event("TRADE_CLOSED");equal(#L.Records(),0)
    complete(w);local r=L.Records()[1];equal(r.kind,"tip_received");equal(r.amount,12345);equal(r.source,"Player trade");equal(r.cost,nil)
    equal(L.Summary().sales,12345);equal(L.Summary().flow,12345);equal(L.Summary().tips,12345)
end)
test("given trade gold is spending with the exact offered amount",function()
    local w,A,T,L=world();offer(w,321,0);w:event("TRADE_CLOSED");complete(w)
    local r=L.Records()[1];equal(r.kind,"tip_given");equal(r.amount,321);equal(L.Summary().spend,321);equal(L.Summary().flow,-321)
end)
test("both trade directions remain separate and cash flow uses their difference",function()
    local w,A,T,L=world();offer(w,500,1200);complete(w)
    equal(#L.Records(),2);equal(L.Summary().sales,1200);equal(L.Summary().spend,500);equal(L.Summary().flow,700)
    equal(L.Summary().byKind.tip_received,1200);equal(L.Summary().byKind.tip_given,-500)
end)
test("a success message before the closed event records the trade once",function()
    local w,A,T,L=world();offer(w,0,100);complete(w);w:event("TRADE_CLOSED");complete(w);equal(#L.Records(),1)
end)
test("repeated success and closure events do not duplicate a completed trade",function()
    local w,A,T,L=world();offer(w,0,100);w:event("TRADE_CLOSED");w:event("TRADE_CLOSED");complete(w);complete(w)
    equal(#L.Records(),1);offer(w,0,100);complete(w);equal(#L.Records(),2)
end)
test("closing or cancelling an accepted trade creates no ledger transfer",function()
    local w,A,T,L=world();offer(w,10,100);w:event("TRADE_CLOSED");equal(#L.Records(),0)
    w:event("TRADE_REQUEST_CANCEL");complete(w);equal(#L.Records(),0)
end)
test("a zero gold completed trade does not create empty ledger entries",function()
    local w,A,T,L=world();offer(w,0,0);complete(w);equal(#L.Records(),0);equal(T.skipped,0)
end)
test("native success can complete the last accepted offers without a separate final acceptance update",function()
    local w,A,T,L=world();w.received=100;w:event("TRADE_SHOW");w:event("TRADE_ACCEPT_UPDATE",1,0)
    equal(#L.Records(),0);w:event("TRADE_CLOSED");complete(w);equal(#L.Records(),1);equal(L.Records()[1].amount,100)
end)
test("money changes invalidate accepted offers until the new amounts are accepted",function()
    local w,A,T,L=world();offer(w,0,100);w.received=200;w:event("TRADE_MONEY_CHANGED");complete(w);equal(#L.Records(),0)
    offer(w,0,100);w.received=250;w:event("TRADE_MONEY_CHANGED");w:event("TRADE_ACCEPT_UPDATE",1,1);complete(w);equal(L.Records()[1].amount,250)
end)
test("clearing acceptance or changing an item invalidates the captured trade agreement",function()
    local w,A,T,L=world();offer(w,0,100);w:event("TRADE_ACCEPT_UPDATE",0,0);complete(w);equal(#L.Records(),0)
    offer(w,0,100);w:event("TRADE_TARGET_ITEM_CHANGED",1);complete(w);equal(#L.Records(),0)
end)
test("restricted and invalid trade gold cannot become ledger entries",function()
    for _,value in ipairs({secret,-1,1000000000001,0/0,"100"})do
        local w,A,T,L=world();offer(w,0,value);complete(w);equal(#L.Records(),0)
    end
end)
test("missing native trade money readers keep automatic tips unavailable",function()
    local w,A,T,L=world();GetTargetTradeMoney=nil;offer(w,0,100);complete(w);equal(T.tradeAPI,false);equal(#L.Records(),0)
end)
test("typed completion names work independently of the localized message text",function()
    local w,A,T,L=world();GetGameMessageInfo=function(code)equal(code,87);return "ERR_TRADE_COMPLETE"end
    offer(w,0,100);w:event("UI_INFO_MESSAGE",87,"Localized success");equal(#L.Records(),1)
end)
test("native trade failures discard the context before any later success message",function()
    local w,A,T,L=world();GetGameMessageInfo=function()return "ERR_TRADE_TARGET_BAG_FULL"end
    offer(w,0,100);w:event("UI_ERROR_MESSAGE",88,"Localized failure");GetGameMessageInfo=nil;complete(w);equal(#L.Records(),0)
end)
test("unrelated UI messages do not consume a valid trade",function()
    local w,A,T,L=world();offer(w,0,100);w:event("UI_INFO_MESSAGE",11,"Other message");complete(w);equal(#L.Records(),1)
end)
test("native close clearing money after hiding the frame preserves final accepted offers",function()
    local w,A,T,L=world();TradeFrame=CreateFrame("Frame");TradeFrame:Show();offer(w,0,100)
    TradeFrame:Hide();w.received=0;w:event("TRADE_MONEY_CHANGED");w:event("TRADE_ACCEPT_UPDATE",0,0);w:event("TRADE_TARGET_ITEM_CHANGED",7);w:event("TRADE_CLOSED");complete(w);equal(L.Records()[1].amount,100)
end)
test("late completion without a current closed trade context is rejected",function()
    local w,A,T,L=world();offer(w,0,100);w:event("TRADE_CLOSED");w:advance(11);T.Tick();complete(w);equal(#L.Records(),0)
end)
test("a player scope change cannot credit another character's trade",function()
    local w,A,T,L=world();offer(w,0,100);w.guid="Player-other";complete(w);equal(#L.Records(),0)
end)
test("disabling trade tracking discards active offers and leaves AH and vendor settings alone",function()
    local w,A,T,L=world();offer(w,0,100);A.EconomyUI.Show("ledger");local E=A.EconomyUI
    E.SetLedgerView("options");E.autoTrade:SetChecked(false);E.autoTrade.scripts.OnClick(E.autoTrade);complete(w)
    equal(#L.Records(),0);equal(A.DB.Settings().trackTrade,false);truth(A.DB.Settings().trackAH);truth(A.DB.Settings().trackVendor)
    local saved=A.DB.data;local w2,A2=fresh(saved);w2:load();equal(A2.DB.Settings().trackTrade,false)
end)
test("confirmed tips persist while an unconfirmed offer does not survive reload",function()
    local w,A,T,L=world();offer(w,0,100);complete(w);offer(w,0,300)
    local saved=A.DB.data;local w2,A2=fresh(saved);w2:load();w2:event("UI_INFO_MESSAGE",1,ERR_TRADE_COMPLETE)
    equal(#A2.Ledger.Records(),1);equal(A2.Ledger.Records()[1].amount,100)
end)
test("both confirmed trade directions queue at capacity and retain their timestamps",function()
    local w,A,T,L=world();L.limit=1;truth(L.Record({kind="buy",name="Existing",quantity=1,amount=1}))
    offer(w,100,200);complete(w);equal(#T.queue,2);local stamp=T.queue[1].input.time
    local w2,A2=fresh(A.DB.data);w2.wall=w.wall+60;w2:load();A2.Transactions.Tick();w2:advance(3);A2.Transactions.Tick()
    equal(#A2.Transactions.queue,0);equal(#A2.Ledger.Records(),3)
    local count=0;for _,r in ipairs(A2.Ledger.Records())do if r.source=="Player trade"then count=count+1;equal(r.time,stamp)end end;equal(count,2)
end)
test("idle trade tracking reads no offers and calls no trade action",function()
    local w,A,T,L=world();local reads=w.tradeReads or 0;local actions=0
    local function action()actions=actions+1 end
    AcceptTrade,CancelTrade,CloseTrade=action,action,action
    for _=1,100 do T.Tick();w:event("UI_INFO_MESSAGE",1,"Unrelated")end
    equal(w.tradeReads or 0,reads);offer(w,0,100);complete(w);equal(actions,0);equal(w.requests,0)
end)
test("a confirmed trade may record during combat without opening addon frames",function()
    local w,A,T,L=world();offer(w,0,100);w.combat=true;complete(w);equal(#L.Records(),1);equal(A.EconomyUI.frame,nil)
end)
test("trade payments can be reclassified without adding a second transaction",function()
    local w,A,T,L=world();offer(w,0,1000);complete(w);A.EconomyUI.Show("ledger");local E=A.EconomyUI
    E.LoadLedger(L.Records()[1]);E.kindDropdown:OpenMenu();truth(E.kindDropdown:Pick("commission"));E.ledgerInputs.cost:SetText(".04");truth(E.RecordLedger())
    equal(#L.Records(),1);equal(L.Records()[1].kind,"commission");equal(L.Records()[1].source,"Player trade");equal(L.Summary().profit,600)
    complete(w);equal(#L.Records(),1)
end)
