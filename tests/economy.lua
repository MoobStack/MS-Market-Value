local fresh,craftingWorld,craftRecipe,row,link,test,equal,near,truth,secret = ...
local function watchWorld(prices,suffix)
    local w,A=fresh();w:load()
    for index,price in ipairs(prices or {1000,1000,1000,500})do
        local snap=A.DB.NewSnapshot(A.Util.MarketKey(),1,w.wall)
        A.DB.AddRow(snap,100,1,price,link(100,suffix),0);truth(A.DB.Commit(snap))
        if index<#(prices or {1,2,3,4})then w:advance(86400)end
    end
    return w,A
end
local function watchDrain(A)
    A.Watchlist.Ensure()
    for _=1,1000 do if not A.Watchlist.job then return end;A.Watchlist.Tick()end
    error("watchlist did not finish")
end
local function serviceWorld()
