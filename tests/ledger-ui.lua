    truth(A.UI.frame:IsShown());truth(A.UI.ledgerShortcut);A.UI.ledgerShortcut.scripts.OnClick()
    equal(A.UI.frame:IsShown(),false);truth(A.EconomyUI.frame:IsShown());equal(A.EconomyUI.mode,"ledger");equal(w.requests,0)
end)
