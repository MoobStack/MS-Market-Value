test("all six type choices select their own rows directly",function()
    local w,A,E=initial()
    for _,kind in ipairs({"sale","buy","vendor_sale","vendor_buy","commission"})do entry(A,kind,100)end
    for _,kind in ipairs({"buy","sale","vendor_buy","vendor_sale","commission","all"})do
        E.filterButtons[kind].scripts.OnClick();equal(E.filterKind,kind);equal(E.ledgerView,"transactions")
        local rows=A.Ledger.View(E.CurrentFilter());equal(#rows,kind=="all"and 5 or 1)
        if kind~="all"then equal(rows[1].kind,kind)end
        truth(string.find(E.filterButtons[kind].text,"|cffffd100",1,true))
    end
    equal(w.requests,0)
end)
