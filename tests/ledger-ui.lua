test("the report separates income spending cash flow and each activity source",function()
    local w,A,E=initial()
    entry(A,"sale",10000,6000,500);entry(A,"buy",3000,nil,100);entry(A,"vendor_sale",500,200)
    entry(A,"vendor_buy",2000);entry(A,"commission",5000,1000,0,500,true);entry(A,"expense",100)
    E.Refresh();local money=A.Util.Money
    equal(E.report.income.text,money(15500));equal(E.report.spend.text,money(5200));equal(E.report.flow.text,"+"..money(10300))
    local expected={sale=9500,buy=3100,vendor_sale=500,vendor_buy=2000,commission=5500,expense=100}
    for kind,amount in pairs(expected)do equal(E.activityRows[kind].value.text,money(amount))end
    equal(E.report.profit.text,"+"..money(3800));equal(E.report.estimate.text,"+"..money(4500))
    local s=A.Ledger.Summary(E.PeriodFilter());equal(s.known,2);equal(s.estimated,1);equal(s.unknown,0)
    equal(s.counts.sale,1);equal(s.counts.commission,1);equal(s.tips,500)
end)
