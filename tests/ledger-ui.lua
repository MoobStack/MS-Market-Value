local fresh,test,equal,truth=...
local function initial()
    local w,A=fresh();w:load();A.auctionOpen=false;A.EconomyUI.Show("ledger");return w,A,A.EconomyUI
end
local function entry(A,kind,amount,cost,fee,tip,estimate,name)
    local ok,why=A.Ledger.Record({kind=kind,name=name or kind,quantity=1,amount=amount,cost=cost,fee=fee or 0,tip=tip or 0,estimatedCost=estimate})
    truth(ok,why)
end

